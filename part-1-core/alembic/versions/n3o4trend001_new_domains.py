def _esc(s: str) -> str:
    return s.replace("'", "''")


def upgrade() -> None:
    now = datetime.now(timezone.utc).isoformat()
    # ---- new domains ----
    for i, (slug, name, icon, desc, cat, order) in enumerate(NEW_DOMAINS):
        did = f"seed-dom2-{i:04d}".ljust(36, "0")[:36]
        op.execute(
            "INSERT INTO curriculum_domains (id, slug, name, icon, description, "
            f"category, order_index, is_active) VALUES ('{did}', '{slug}', "
            f"'{_esc(name)}', '{_esc(icon)}', '{_esc(desc)}', '{cat}', {order}, 1)"
        )
    # ---- new modules ----
    mi = 0
    for slug, _name, _icon, _desc, _cat, _order in NEW_DOMAINS:
        for j, (mslug, mname, mdesc, days) in enumerate(NEW_MODULES.get(slug, [])):
            mid = f"seed-mod2-{mi:04d}".ljust(36, "0")[:36]
            op.execute(
                "INSERT INTO curriculum_modules (id, domain_slug, slug, name, "
                f"description, order_index, estimated_days) VALUES ('{mid}', "
                f"'{slug}', '{mslug}', '{_esc(mname)}', '{_esc(mdesc)}', {j}, {days})"
            )
            mi += 1
    # ---- extra modules for existing domains ----
    for domain_slug, mods in EXTRA_MODULES.items():
        for j, (mslug, mname, mdesc, days) in enumerate(mods):
            mid = f"seed-modx-{mi:04d}".ljust(36, "0")[:36]
            op.execute(
                "INSERT INTO curriculum_modules (id, domain_slug, slug, name, "
                f"description, order_index, estimated_days) VALUES ('{mid}', "
                f"'{domain_slug}', '{mslug}', '{_esc(mname)}', '{_esc(mdesc)}', {90 + j}, {days})"
            )
            mi += 1
    # ---- starter questions ----
    for i, (domain, module, diff, prompt, choices, ans, expl, companies) in enumerate(STARTER_QUESTIONS):
        qid = f"seed-qst2-{i:04d}".ljust(36, "0")[:36]
        op.execute(
            "INSERT INTO curriculum_questions (id, domain_slug, module_slug, lesson_id, "
            "difficulty, qtype, prompt, choices, answer_index, explanation, company_tags, created_at) "
            f"VALUES ('{qid}', '{domain}', '{module}', NULL, {diff}, 'mcq', "
            f"'{_esc(prompt)}', '{_esc(json.dumps(choices))}', {ans}, "
            f"'{_esc(expl)}', '{_esc(json.dumps(companies))}', '{now}')"
        )


def downgrade() -> None:
    for i in range(len(STARTER_QUESTIONS)):
        qid = f"seed-qst2-{i:04d}".ljust(36, "0")[:36]
        op.execute(f"DELETE FROM curriculum_questions WHERE id = '{qid}'")
    # modules (new + extra)
    total_mods = sum(len(v) for v in NEW_MODULES.values()) + sum(len(v) for v in EXTRA_MODULES.values())
    for mi in range(total_mods):
        for prefix in ("seed-mod2-", "seed-modx-"):
            mid = f"{prefix}{mi:04d}".ljust(36, "0")[:36]
            op.execute(f"DELETE FROM curriculum_modules WHERE id = '{mid}'")
    for i in range(len(NEW_DOMAINS)):
        did = f"seed-dom2-{i:04d}".ljust(36, "0")[:36]
        op.execute(f"DELETE FROM curriculum_domains WHERE id = '{did}'")
