GD_CATEGORIES = ["tech", "social", "abstract"]


def get_gd_topics(category: str = "", difficulty: int = 0) -> list[dict]:
    """Filter GD topics by category and/or max difficulty."""
    out = GD_TOPICS
    if category:
        out = [t for t in out if t["category"] == category]
    if difficulty:
        out = [t for t in out if t["difficulty"] <= difficulty]
    return out


def summary() -> dict:
    cats: dict[str, int] = {}
    for t in GD_TOPICS:
        cats[t["category"]] = cats.get(t["category"], 0) + 1
    return {"total": len(GD_TOPICS), "by_category": cats}
