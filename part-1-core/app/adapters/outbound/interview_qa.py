def get_interview_qa(category: str = "", subcategory: str = "") -> list[dict]:
    """All Q&A, optionally filtered by category ('hr'/'technical') and subcategory."""
    items = _all_items()
    if category:
        items = [q for q in items if q["category"] == category]
    if subcategory:
        items = [q for q in items if q["subcategory"] == subcategory]
    return items


def get_companies() -> list[str]:
    """Sorted unique company slugs across all Q&A."""
    seen: set[str] = set()
    for q in _all_items():
        seen.update(q.get("companies", []))
    return sorted(seen)


def get_by_company(company: str) -> list[dict]:
    """Q&A frequently asked at a given company."""
    return [q for q in _all_items() if company in q.get("companies", [])]


def get_random(count: int = 5, category: str = "") -> list[dict]:
    """Random sample — no repeats within one draw."""
    import random

    items = get_interview_qa(category=category) if category else _all_items()
    return random.sample(items, min(count, len(items)))


def summary() -> dict:
    items = _all_items()
    return {
        "total": len(items),
        "hr": sum(1 for q in items if q["category"] == "hr"),
        "technical": sum(1 for q in items if q["category"] == "technical"),
        "subcategories": sorted({q["subcategory"] for q in items}),
        "companies": get_companies(),
    }

