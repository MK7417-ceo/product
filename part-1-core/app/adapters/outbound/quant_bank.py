# ---------------------------------------------------------------- helpers ---
def get_types(section: str = "") -> list[dict]:
    """Aptitude types, optionally filtered by section."""
    if section:
        return [t for t in APTITUDE_TYPES if t["section"] == section]
    return APTITUDE_TYPES


def get_questions(type_id: str = "", section: str = "") -> list[dict]:
    """Questions filtered by type and/or section."""
    out = APTITUDE_QUESTIONS
    if type_id:
        out = [q for q in out if q["type"] == type_id]
    if section:
        type_ids = {t["id"] for t in APTITUDE_TYPES if t["section"] == section}
        out = [q for q in out if q["type"] in type_ids]
    return out


def get_trick(type_id: str) -> dict | None:
    """The shortcut trick for a type."""
    for t in APTITUDE_TYPES:
        if t["id"] == type_id:
            return {"trick_title": t["trick_title"], "trick": t["trick"],
                    "trick_example": t["trick_example"]}
    return None


def summary() -> dict:
    by_type: dict[str, int] = {}
    for q in APTITUDE_QUESTIONS:
        by_type[q["type"]] = by_type.get(q["type"], 0) + 1
    by_section: dict[str, int] = {}
    type_to_section = {t["id"]: t["section"] for t in APTITUDE_TYPES}
    for q in APTITUDE_QUESTIONS:
        s = type_to_section.get(q["type"], "?")
        by_section[s] = by_section.get(s, 0) + 1
    return {"types": len(APTITUDE_TYPES), "total": len(APTITUDE_QUESTIONS),
            "by_type": by_type, "by_section": by_section}
